// The catalog layer: the searchable pickers, the customer's own entries,
// «تفاصيل إضافية» titled for what the item is, and «حفظ وإضافة التالي».
//
// Every picker level uses its domain's own noun — a car has a «الشركة
// المصنعة», a watch a «البراند», a painting a «الفنان» — and every level has
// its own way out of the catalog: «+ إضافة … غير موجود».

const noun = (key, pick, search, add, confirm) => ({
  [`catalog.pick.${key}`]: pick,
  [`catalog.search.${key}`]: search,
  [`catalog.add.${key}`]: add,
  [`catalog.confirm.${key}`]: confirm,
});

